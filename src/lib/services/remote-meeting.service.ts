'use client';

/**
 * Service de gestion des réunions à distance
 * V1: Génération de liens Jitsi (pas d'OAuth nécessaire)
 *
 * Architecture prévue pour OAuth future:
 * - Interface RemoteMeetingProvider
 * - Implémentations: JitsiProvider, ZoomProvider, GoogleMeetProvider, TeamsProvider
 */

import { createClient } from '@/lib/supabase/client';

// Helper: Create untyped client for tables/views not yet in generated types
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const createUntypedClient = () => createClient() as any;

// ============================================================================
// Types
// ============================================================================

export type RemoteMeetingProvider = 'jitsi' | 'zoom' | 'meet' | 'teams' | 'webex' | 'other';

export interface CreateRemoteMeetingInput {
  /** ID de la copropriété */
  coproId: string;
  /** ID de l'AG */
  agId: string;
  /** Titre de la réunion (utilisé pour générer le room name) */
  title: string;
  /** Date/heure de début (ISO string) */
  startsAt: string;
  /** Date/heure de fin optionnelle (ISO string) */
  endsAt?: string;
  /** Provider préféré (défaut: jitsi) */
  provider?: RemoteMeetingProvider;
}

export interface RemoteMeetingResult {
  /** Provider utilisé */
  provider: RemoteMeetingProvider;
  /** URL de la réunion */
  url: string;
  /** Nom/ID de la room */
  roomName: string;
  /** Indique si c'est un lien auto-généré ou externe */
  autoGenerated: boolean;
}

export interface SavedRemoteMeeting extends RemoteMeetingResult {
  /** ID de l'AG */
  agId: string;
  /** Date de création */
  createdAt: string;
}

// ============================================================================
// Jitsi Provider (V1 - Pas d'OAuth)
// ============================================================================

const JITSI_BASE_URL = 'https://meet.jit.si';

/**
 * Génère un nom de room Jitsi unique et lisible
 */
function generateJitsiRoomName(coproId: string, agId: string, title: string): string {
  // Nettoyer le titre pour créer un slug
  const slug = title
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // Supprimer accents
    .replace(/[^a-z0-9]+/g, '-') // Remplacer caractères spéciaux
    .replace(/^-+|-+$/g, '') // Supprimer tirets début/fin
    .substring(0, 30); // Limiter longueur

  // Ajouter un hash court pour unicité
  const hash = agId.substring(0, 8);

  return `coproflex-${slug}-${hash}`;
}

/**
 * Crée un lien Jitsi Meet
 */
function createJitsiMeeting(input: CreateRemoteMeetingInput): RemoteMeetingResult {
  const roomName = generateJitsiRoomName(input.coproId, input.agId, input.title);
  const url = `${JITSI_BASE_URL}/${roomName}`;

  return {
    provider: 'jitsi',
    url,
    roomName,
    autoGenerated: true,
  };
}

// ============================================================================
// Provider Detection
// ============================================================================

/**
 * Détecte le provider à partir d'une URL de réunion
 */
export function detectProviderFromUrl(url: string): RemoteMeetingProvider {
  if (!url) return 'other';

  const urlLower = url.toLowerCase();

  if (urlLower.includes('zoom.us') || urlLower.includes('zoom.com')) {
    return 'zoom';
  }
  if (urlLower.includes('meet.google.com')) {
    return 'meet';
  }
  if (urlLower.includes('teams.microsoft.com') || urlLower.includes('teams.live.com')) {
    return 'teams';
  }
  if (urlLower.includes('webex.com')) {
    return 'webex';
  }
  if (urlLower.includes('meet.jit.si') || urlLower.includes('jitsi')) {
    return 'jitsi';
  }

  return 'other';
}

