/**
 * Crée une réunion à distance pour une AG
 *
 * @param input Paramètres de création
 * @returns Résultat avec URL et provider
 *
 * @example
 * const meeting = await createRemoteMeeting({
 *   coproId: 'xxx',
 *   agId: 'yyy',
 *   title: 'AG Ordinaire 2026',
 *   startsAt: '2026-04-15T19:00:00',
 * });
 * // meeting.url = 'https://meet.jit.si/coproflex-ag-ordinaire-2026-yyy12345'
 */
export async function createRemoteMeeting(
  input: CreateRemoteMeetingInput
): Promise<RemoteMeetingResult> {
  const provider = input.provider || 'jitsi';

  // V1: Seul Jitsi est supporté (pas d'OAuth)
  // Futur: switch sur provider pour appeler l'API appropriée
  switch (provider) {
    case 'jitsi':
      return createJitsiMeeting(input);

    // TODO: Implémenter avec OAuth
    case 'zoom':
    case 'meet':
    case 'teams':
    case 'webex':
      // Provider requires OAuth, falling back to Jitsi
      return createJitsiMeeting(input);

    default:
      return createJitsiMeeting(input);
  }
}

/**
 * Sauvegarde le lien de réunion dans la base de données (ag_meetings)
 */
export async function saveRemoteMeetingToAg(
  agId: string,
  coproId: string,
  meeting: RemoteMeetingResult
): Promise<boolean> {
  const supabase = createUntypedClient();

  const { error } = await supabase
    .from('ag_meetings')
    .update({
      remote_meeting_url: meeting.url,
      remote_meeting_provider: meeting.provider,
    })
    .eq('id', agId)
    .eq('copro_id', coproId);

  if (error) {
    console.error('[remote-meeting] Error saving to DB:', error);
    return false;
  }

  return true;
}

/**
 * Récupère le lien de réunion existant pour une AG
 */
export async function getRemoteMeetingFromAg(
  agId: string
): Promise<SavedRemoteMeeting | null> {
  const supabase = createUntypedClient();

  const { data, error } = await supabase
    .from('ag_meetings')
    .select('id, remote_meeting_url, remote_meeting_provider, created_at')
    .eq('id', agId)
    .single();

  if (error || !data?.remote_meeting_url) {
    return null;
  }

  return {
    agId: data.id,
    url: data.remote_meeting_url,
    provider: data.remote_meeting_provider || 'other',
    roomName: extractRoomName(data.remote_meeting_url),
    autoGenerated: data.remote_meeting_url.includes('meet.jit.si/coproflex-'),
    createdAt: data.created_at,
  };
}

/**
 * Extrait le nom de room d'une URL de réunion
 */
function extractRoomName(url: string): string {
  try {
    const urlObj = new URL(url);
    return urlObj.pathname.replace(/^\/+/, '');
  } catch {
    return url;
  }
}

/**
 * Crée et sauvegarde une réunion à distance en une seule opération (idempotent)
 * Ne recrée pas le lien s'il existe déjà
 */
export async function ensureRemoteMeeting(
  input: CreateRemoteMeetingInput
): Promise<RemoteMeetingResult> {
  // Vérifier si un lien existe déjà
  const existing = await getRemoteMeetingFromAg(input.agId);
  if (existing) {
    return {
      provider: existing.provider,
      url: existing.url,
      roomName: existing.roomName,
      autoGenerated: existing.autoGenerated,
    };
  }

  // Créer un nouveau lien
  const meeting = await createRemoteMeeting(input);

  // Sauvegarder en DB
  await saveRemoteMeetingToAg(input.agId, input.coproId, meeting);

  return meeting;
}

/**
 * Supprime le lien de réunion d'une AG
 */
export async function removeRemoteMeetingFromAg(
  agId: string,
  coproId: string
): Promise<boolean> {
  const supabase = createUntypedClient();

  const { error } = await supabase
    .from('ag_meetings')
    .update({
      remote_meeting_url: null,
      remote_meeting_provider: null,
    })
    .eq('id', agId)
    .eq('copro_id', coproId);

  if (error) {
    console.error('[remote-meeting] Error removing from DB:', error);
    return false;
  }

  return true;
}
